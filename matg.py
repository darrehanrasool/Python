print("Q9 =", answer9)



# QUESTION 10
# [sin(x) + cos(x)] / [sin(x) - cos(x)]

x10 = math.radians(60)

answer10 = (math.sin(x10) + math.cos(x10)) / (math.sin(x10) - math.cos(x10))

print("Q10 =", answer10)



